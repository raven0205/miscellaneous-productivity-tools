import os
import sqlite3
import uuid
import json
import logging
from flask import Flask, jsonify, request, render_template, Response, g
from prometheus_client import Counter, Gauge, generate_latest, REGISTRY

app = Flask(__name__)

# ----------------- Structured Logging Setup -----------------
class JSONFormatter(logging.Formatter):
    def format(self, record):
        log_record = {
            'timestamp': self.formatTime(record, self.datefmt),
            'level': record.levelname,
            'message': record.getMessage(),
            'trace_id': getattr(record, 'trace_id', 'N/A')
        }
        return json.dumps(log_record)

logger = logging.getLogger('ai_marketing_app')
logger.setLevel(logging.INFO)
handler = logging.StreamHandler()
handler.setFormatter(JSONFormatter())
logger.addHandler(handler)

@app.before_request
def before_request():
    # Generate a trace ID for structured logs and tracing
    g.trace_id = request.headers.get('X-Trace-Id', str(uuid.uuid4()))

def log_info(msg):
    # Logs message without customer data
    logger.info(msg, extra={'trace_id': getattr(g, 'trace_id', 'N/A')})

# ----------------- Database Setup -----------------
DB_FILE = 'marketing.db'

def init_db():
    with sqlite3.connect(DB_FILE) as conn:
        c = conn.cursor()
        c.execute('''
            CREATE TABLE IF NOT EXISTS campaign_drafts (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                generated_subject TEXT NOT NULL,
                generated_body TEXT NOT NULL,
                status TEXT DEFAULT 'pending'
            )
        ''')
        # Insert dummy data if empty
        c.execute('SELECT COUNT(*) FROM campaign_drafts')
        if c.fetchone()[0] == 0:
            c.execute("INSERT INTO campaign_drafts (generated_subject, generated_body, status) VALUES (?, ?, ?)",
                      ("Did you forget something?", "Your cart misses you. Get 10% off today!", "pending"))
        conn.commit()

init_db()

# ----------------- Prometheus Metrics -----------------
revenue_generated = Counter('app_revenue_generated_total', 'Total revenue generated by AI campaigns')
conversion_rate = Gauge('app_conversion_rate', 'Current conversion rate of active AI campaigns')
emails_sent = Counter('app_emails_sent_total', 'Total AI emails sent successfully')
failed_approvals = Counter('app_failed_approvals_total', 'Total AI campaigns rejected by human')
system_alert_status = Gauge('app_alert_status', 'System alert status: 0=OK, 1=Warning, 2=Critical')

# Set some defaults
conversion_rate.set(4.2)
system_alert_status.set(0)

# ----------------- Routes -----------------
@app.route('/')
def index():
    return render_template('index.html')

@app.route('/api/metrics')
def get_metrics():
    with sqlite3.connect(DB_FILE) as conn:
        c = conn.cursor()
        c.execute("SELECT COUNT(*) FROM campaign_drafts WHERE status='pending'")
        pending = c.fetchone()[0]
        
    return jsonify({
        'rpr': 2.5 + (revenue_generated._value.get() / 100 if revenue_generated._value.get() else 0),
        'conversionRate': conversion_rate._value.get(),
        'pendingApprovals': pending,
        'alertStatus': 'critical' if system_alert_status._value.get() == 2 else 'ok'
    })

@app.route('/api/approvals')
def get_approvals():
    with sqlite3.connect(DB_FILE) as conn:
        conn.row_factory = sqlite3.Row
        c = conn.cursor()
        c.execute("SELECT * FROM campaign_drafts WHERE status='pending'")
        rows = c.fetchall()
        return jsonify([dict(ix) for ix in rows])

@app.route('/api/approvals/<int:id>/<action>', methods=['POST'])
def process_approval(id, action):
    log_info(f"Processing approval action: {action} for campaign draft")
    with sqlite3.connect(DB_FILE) as conn:
        c = conn.cursor()
        if action == 'approve':
            c.execute("UPDATE campaign_drafts SET status='approved' WHERE id=?", (id,))
            emails_sent.inc()
            revenue_generated.inc(15.5)
            log_info("Campaign approved and email execution triggered")
        elif action == 'reject':
            c.execute("UPDATE campaign_drafts SET status='rejected' WHERE id=?", (id,))
            failed_approvals.inc()
            log_info("Campaign rejected by human-in-the-loop")
        conn.commit()
    return jsonify({'success': True, 'trace_id': g.trace_id})

@app.route('/api/prom-metrics')
def prom_metrics():
    return Response(generate_latest(REGISTRY), mimetype="text/plain")

@app.route('/webhook/alert', methods=['POST'])
def handle_alert():
    data = request.json or {}
    alerts = data.get('alerts', [])
    for alert in alerts:
        if alert.get('status') == 'firing':
            if alert.get('labels', {}).get('alertname') == 'HighRejectionRate':
                print("Responder Agent: High rejection rate detected. Pausing AI generation.")
                system_alert_status.set(2)
        elif alert.get('status') == 'resolved':
            print("Responder Agent: Alert resolved. Resuming normal operations.")
            system_alert_status.set(0)
    return jsonify({'status': 'processed', 'trace_id': g.trace_id})

if __name__ == '__main__':
    app.run(host='0.0.0.0', port=3000)
